def img(src_dir, key, out):
    d = os.path.join(SRC, src_dir)
    for sub in ("photos-A", "photos-B"):
        for f in sorted(os.listdir(os.path.join(d, sub))):
            if f.startswith(key + "-"):
                im = Image.open(os.path.join(d, sub, f)).convert("RGB")
                if im.width > 1400: im = im.resize((1400, round(1400 * im.height / im.width)), Image.LANCZOS)
                im.save(os.path.join(ROOT, "images/blog", out), "JPEG", quality=84, optimize=True, progressive=True)
                return
    raise SystemExit(f"no photo {src_dir} {key}")

